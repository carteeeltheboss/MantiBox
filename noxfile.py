"""Single source of truth for every project command.

AGENTS.md names ``make <target>`` as the canonical interface. GNU make is not
available on the Windows host this project is developed on, so the Makefile is a
thin wrapper that delegates here: the same commands then work natively on
Windows (``nox -s check``) and in CI / containers / WSL (``make check``).
See ADR 0002.
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

import nox

nox.options.default_venv_backend = "venv"
nox.options.reuse_existing_virtualenvs = True
nox.options.sessions = ["check"]

PYTHON = "3.12"
ROOT = Path(__file__).parent.resolve()

# Markers excluded from the fast gate. `integration` needs the compose stack,
# `gpu` needs a CUDA device, `slow` is minutes-long by design.
FAST_TESTS = "not integration and not gpu and not slow"

# Torch CUDA wheels are not on PyPI's default index.
TORCH_INDEX = "https://download.pytorch.org/whl/cu124"


def _install(session: nox.Session, extra: str = "dev") -> None:
    session.install("--upgrade", "pip", silent=True)
    session.install("-e", f".[{extra}]", silent=True)


@nox.session(python=PYTHON)
def lint(session: nox.Session) -> None:
    """ruff check + format --check (read-only)."""
    _install(session)
    session.run("ruff", "check", ".")
    session.run("ruff", "format", "--check", ".")


@nox.session(python=PYTHON)
def format(session: nox.Session) -> None:
    """Apply ruff fixes and formatting in place."""
    _install(session)
    session.run("ruff", "check", "--fix", ".")
    session.run("ruff", "format", ".")


@nox.session(python=PYTHON)
def types(session: nox.Session) -> None:
    """mypy --strict over src/."""
    _install(session)
    session.run("mypy", "src")


@nox.session(python=PYTHON)
def test(session: nox.Session) -> None:
    """Unit tests. No services, no GPU, no torch required."""
    _install(session)
    session.run(
        "pytest",
        "-m",
        FAST_TESTS,
        "--cov=maintidoc",
        "--cov-report=term-missing:skip-covered",
        *session.posargs,
    )


@nox.session(python=PYTHON)
def check(session: nox.Session) -> None:
    """The AGENTS.md gate: lint + types + test in one venv. Must pass pre-commit."""
    _install(session)
    session.run("ruff", "check", ".")
    session.run("ruff", "format", "--check", ".")
    session.run("mypy", "src")
    session.run("pytest", "-m", FAST_TESTS, *session.posargs)


@nox.session(python=PYTHON)
def test_all(session: nox.Session) -> None:
    """Every test including integration. Requires `nox -s compose_up` first."""
    _install(session)
    session.run("pytest", *session.posargs)


@nox.session(python=PYTHON)
def lock(session: nox.Session) -> None:
    """Regenerate requirements.lock.txt (host/CI install) from pyproject."""
    _install(session)
    frozen = session.run("pip", "freeze", external=True, silent=True)
    header = (
        "# Generated by `nox -s lock`. Do not edit by hand.\n"
        "# Exact pins for the core + dev install; see pyproject.toml for the\n"
        "# lower bounds and the ADR that justified each dependency.\n"
    )
    out = ROOT / "requirements.lock.txt"
    out.write_text(header + str(frozen).rstrip() + "\n", encoding="utf-8")
    session.log(f"wrote {out}")


@nox.session(python=PYTHON)
def lock_ml(session: nox.Session) -> None:
    """Regenerate requirements.ml.lock.txt by resolving inside a Linux container.

    Resolving the ML extra on Windows would pin Windows/CPU wheels, which is
    wrong for the CUDA image — so the resolution happens in linux/amd64.
    """
    session.run(
        "docker",
        "run",
        "--rm",
        "--platform",
        "linux/amd64",
        "-v",
        f"{ROOT}:/work",
        "-w",
        "/work",
        "python:3.12-slim",
        "bash",
        "-c",
        "pip install --upgrade pip && "
        f"pip install -e '.[ml,tracking]' --extra-index-url {TORCH_INDEX} && "
        "pip freeze > /tmp/frozen.txt && "
        "{ echo '# Generated by `nox -s lock_ml` inside linux/amd64. Do not edit.'; "
        "echo '# Consumed by the CUDA stage of Dockerfile.vlm.'; "
        "cat /tmp/frozen.txt; } > requirements.ml.lock.txt",
        external=True,
    )
    session.log(f"wrote {ROOT / 'requirements.ml.lock.txt'}")


@nox.session(python=PYTHON)
def corpus(session: nox.Session) -> None:
    """Generate the synthetic corpus (SPEC §2): PDFs, figures, manifest."""
    _install(session)
    session.run("python", "scripts/generate_corpus.py", *session.posargs)


@nox.session(python=PYTHON)
def ingest(session: nox.Session) -> None:
    """Run the ingestion pipeline against the generated corpus."""
    _install(session)
    session.run("python", "-m", "maintidoc.cli", "ingest", *session.posargs)


@nox.session(python=PYTHON)
def eval(session: nox.Session) -> None:
    """Run the eval harness (SPEC §10) and log metrics."""
    _install(session, extra="dev,tracking")
    session.run("python", "-m", "eval.run", *session.posargs)


@nox.session(python=PYTHON)
def bench_vlm(session: nox.Session) -> None:
    """Benchmark the VLM on the real device (SPEC §11). Needs the gpu profile."""
    _install(session)
    session.run("python", "-m", "maintidoc.cli", "bench-vlm", *session.posargs)


def _compose(session: nox.Session, *args: str) -> None:
    session.run(
        "docker",
        "compose",
        *args,
        external=True,
        env={
            **os.environ,
            "COMPOSE_PROJECT_NAME": os.environ.get("COMPOSE_PROJECT_NAME", "maintidoc"),
        },
    )


@nox.session(python=PYTHON)
def compose_up(session: nox.Session) -> None:
    """Start the portable CPU baseline stack. Add `-- --profile gpu` for CUDA."""
    _compose(session, "up", "-d", "--build", "--remove-orphans", *session.posargs)
    _compose(session, "ps")


@nox.session(python=PYTHON)
def compose_down(session: nox.Session) -> None:
    _compose(session, "down", *session.posargs)


@nox.session(python=PYTHON)
def compose_logs(session: nox.Session) -> None:
    _compose(session, "logs", "--tail=200", *session.posargs)


@nox.session(python=PYTHON)
def doctor(session: nox.Session) -> None:
    """Report what this machine can actually run: device, VRAM, services, models."""
    _install(session)
    session.run("python", "-m", "maintidoc.cli", "doctor", *session.posargs)


if __name__ == "__main__":  # pragma: no cover
    sys.exit(nox.main())
